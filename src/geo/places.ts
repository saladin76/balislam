/** «قرطبة» أو «مكان | 35.2, 31.7» → اسم وإحداثيات، أو null إن لم يُعرف المكان */
export const parsePlace = (line: string): { name: string; at: [number, number] } | null => {
  const [rawName, coords] = line.split("|").map((x) => x.trim());
  const name = rawName ?? "";
  if (!name) return null;
  if (coords) {
    const [lon, lat] = coords.split(/[,،\s]+/).map(Number);
    if (Number.isFinite(lon) && Number.isFinite(lat)) return { name, at: [lon!, lat!] };
  }
  const hit = places[name] ?? places[name.replace(/^ال/, "")] ?? Object.entries(places).find(([k]) => k.replace(/^ال/, "") === name.replace(/^ال/, ""))?.[1];
  return hit ? { name, at: hit } : null;
};
