import React, { useEffect, useRef, useState } from "react";
import { api, type ScenePrepareRead, type VoiceGenerationPlan } from "../api";
import { ownerMessage } from "../serverMessages";
import { nameSceneIds, sceneName, sceneNames } from "./sceneNames";
import { tones, toneIds } from "../../../src/voice/tones";
import { OwnerText } from "../ui/OwnerText";
import { DRAFTS, LETTERS, SCENES, SENTENCES, countAr } from "../../../src/i18n/count";

/**
 * M1: when the episode has no tone the voice cannot be made and preparing stops at once. The choice is
 * offered where the owner reads it: «لا نبرة للحلقة — اخترها هنا». Sets the episode tone only (plan.tone).
 */
const countSentences = (n: number) => (n === 1 ? "جملة واحدة" : n === 2 ? "جملتين" : n <= 10 ? `${n.toLocaleString("ar-EG")} جمل` : `${n.toLocaleString("ar-EG")} جملة`);
export const EpisodeTonePick: React.FC<{ onPick: (tone: string) => Promise<void>; scenes: string[]; order: string[]; episodeId?: string; channelId?: string }> = ({ onPick, scenes, order, episodeId, channelId }) => {
  const [busy, setBusy] = useState(false);
  /**
   * D97: before the tone is saved, what it would invalidate is read (nothing is generated). Takes recorded with a
   * known tone keep it; when some existing recordings would still need a new paid generation, the owner is told
   * how many and decides: «اختر النبرة على أي حال» or «تراجع». Nothing is generated by either button.
   */
  const [warn, setWarn] = useState<{ tone: string; sentences: number; scenes: string[] } | null>(null);
  const apply = (t: string) => { setWarn(null); setBusy(true); void onPick(t).catch(() => {}).finally(() => setBusy(false)); };
  const choose = async (t: string) => {
    if (!episodeId || !channelId) return apply(t);
    setBusy(true);
    try {
      const r = await api.toneImpact(episodeId, channelId, t);
      if (r.sentences.length || r.scenes.length) { setWarn({ tone: t, sentences: r.sentences.length, scenes: r.scenes }); setBusy(false); return; }
    } catch { /* the check is a guard, not a gate: on error the owner is still asked below */
      setWarn({ tone: t, sentences: -1, scenes: [] }); setBusy(false); return;
    }
    setBusy(false);
    apply(t);
  };
  const name = (t: string) => (t in tones ? tones[t as keyof typeof tones].nameAr : t);
  return (
    <label className="prep-tone">
      <span>لا نبرة للحلقة{scenes.length ? ` (${sceneNames(order, scenes, 4)})` : ""} — اخترها هنا:</span>{" "}
      <select value="" disabled={busy || Boolean(warn)} aria-label="نبرة الصوت في الحلقة"
        onChange={(e) => { const t = e.target.value; if (!t) return; void choose(t); }}>
        <option value="">اختر نبرة الحلقة…</option>
        {toneIds.map((t) => <option key={t} value={t}>{tones[t].nameAr}: {tones[t].useAr}</option>)}
      </select>
      {warn ? (
        <span className="prep-tone-warn" role="alert">
          {warn.sentences < 0 ? <>تعذّر حساب أثر نبرة «{name(warn.tone)}» على التسجيلات القائمة.</>
            : <>نبرة «{name(warn.tone)}» تغيّر صوت تسجيلات قائمة: سيحتاج{" "}
              {warn.sentences ? <b>{countSentences(warn.sentences)}</b> : null}
              {warn.sentences && warn.scenes.length ? " و" : ""}
              {warn.scenes.length ? <b>{ar(warn.scenes.length)} {warn.scenes.length === 1 ? "مشهد" : "مشهدًا"} ({sceneNames(order, warn.scenes, 4)})</b> : null}
              {" "}توليدًا جديدًا مدفوعًا.</>}
          {" "}لا يُولَّد شيء الآن، والتسجيلات القائمة تبقى محفوظة.{" "}
          <button type="button" className="prep-link" onClick={() => apply(warn.tone)}>اختر النبرة على أي حال</button>{" — "}
          <button type="button" className="prep-link" onClick={() => setWarn(null)}>تراجع</button>
        </span>
      ) : null}
    </label>
  );
};

const ar = (n: number) => n.toLocaleString("ar-EG");

/** «جاهز لتوليد صوت N جملة في M مشهد — نحو X حرف من الرصيد» (owner decision 15–16 Nov). */
export const voicePlanLine = (p: Pick<VoiceGenerationPlan, "sentences" | "scenes" | "chars">) =>
  `جاهز لتوليد صوت ${countAr(p.sentences, SENTENCES)} في ${countAr(p.scenes.length, SCENES)} — نحو ${countAr(p.chars, LETTERS)} من الرصيد`;
const EXCLUDED_WHY = { verse: "آية: تلاوتك", basmala: "البسملة: تسجيلك، وجمل الراوي فيه تُحسب", quran: "نصه فيه آية: انقلها إلى مشهد آية" } as const;
/** The scenes the cloned voice never receives, named («المشهد ٤ (آية: تلاوتك)»). */
export const voicePlanExcluded = (p: Pick<VoiceGenerationPlan, "excluded">, order: string[]) =>
  p.excluded.map((x) => `${sceneName(order, x.id)} (${EXCLUDED_WHY[x.reason]})`).join("، ");

/**
 * Owner decision (15–16 Nov): after «اعتمد التجهيز» nothing paid starts on its own. This panel says what the voice
 * would cost and waits for his press: «ولّد الصوت الآن», then a confirmation naming the cost; only «نعم، ولّد الصوت»
 * sends the request (bound to the plan he read by its fingerprint). «تراجع» sends nothing.
 */
export const VoicePlanPanel: React.FC<{
  plan: VoiceGenerationPlan; order: string[]; voiceKey: boolean; busy: boolean;
  onGenerate: (fingerprint: string) => void; onOpenSettings?: () => void;
}> = ({ plan, order, voiceKey, busy, onGenerate, onOpenSettings }) => {
  const [confirming, setConfirming] = useState(false);
  useEffect(() => setConfirming(false), [plan.fingerprint]);
  return (
    <div className="prep-voice-plan" role="group" aria-label="توليد الصوت">
      <span role="status">{voicePlanLine(plan)}.</span>
      {plan.excluded.length ? <span className="prep-voice-excluded"> لا يُرسل إلى الصوت المستنسخ أبدًا: {voicePlanExcluded(plan, order)}.</span> : null}
      {" "}
      {!voiceKey ? (
        <>لا يوجد مفتاح صوت.{onOpenSettings ? <> <button type="button" className="prep-link" onClick={onOpenSettings}>الاتصالات والمفاتيح</button></> : null}</>
      ) : confirming ? (
        <span role="alert">
          سيُصرف نحو {countAr(plan.chars, LETTERS)} من رصيد الصوت. هل تولّده الآن؟{" "}
          <button type="button" className="btn primary" disabled={busy} onClick={() => { setConfirming(false); onGenerate(plan.fingerprint); }}>نعم، ولّد الصوت</button>{" "}
          <button type="button" className="btn ghost" onClick={() => setConfirming(false)}>تراجع</button>
        </span>
      ) : (
        <button type="button" className="btn" disabled={busy} onClick={() => setConfirming(true)}
          title="لا يُولَّد شيء قبل تأكيدك؛ والمسودات المجانية تُجهَّز دون انتظاره">ولّد الصوت الآن</button>
      )}
    </div>
  );
};

/**
 * Preparing the scenes (funnel v3): it starts ON ITS OWN right after «اعتمد التجهيز» (step ١) and pre-renders, free,
 * every scene whose voice already exists. The missing voice is never generated on its own (owner decision 15–16 Nov):
 * `VoicePlanPanel` shows its count and cost and waits for «ولّد الصوت الآن» + confirmation. This is
 * only a status line «جاهز ١٢ من ١١٤» with «أوقف» while it runs and «استأنف» when it stopped (a Studio restart,
 * «أوقف», or an error). A finished run with scenes still waiting (no voice yet) says why instead of offering a
 * button that would skip them again. «أنتج كل المشاهد الجاهزة» renders every scene whose voice exists, generating
 * nothing (D145). Drafts are not approvals: each scene is still watched and approved by the owner, in any order.
 */
export const PrepareAll: React.FC<{
  episodeId: string;
  channelId: string;
  /** From the scene ledger read: approved + submitted + current drafts, of all scenes. */
  prepared?: { ready: number; total: number };
  onOpenSettings?: () => void;
  /** Called whenever a draft lands or the queue finishes, to refresh the ledger read. */
  onChanged?: () => void;
  /** Scene ids in episode order: the owner reads «المشهد ٣», never «c1-s3» (audit item 11). */
  order?: string[];
  className?: string;
  /** The queue as last read (step ٢ uses it to say «يُجهَّز الآن» under a scene that is not ready yet). */
  onJob?: (job: ScenePrepareRead["job"]) => void;
  /** M1: set the episode's tone from the stopped line (the page saves its plan); then «استأنف إنتاج المسودات». */
  onEpisodeTone?: (tone: string) => Promise<void>;
}> = ({ episodeId, channelId, prepared, onOpenSettings, onChanged, order = [], className, onJob, onEpisodeTone }) => {
  const [info, setInfo] = useState<ScenePrepareRead | null>(null);
  const [error, setError] = useState("");
  const [starting, setStarting] = useState(false);
  const seen = useRef("");
  const changed = useRef(onChanged);
  changed.current = onChanged;
  const jobSeen = useRef(onJob);
  jobSeen.current = onJob;

  const load = async () => {
    try {
      const r = await api.scenePrepare(episodeId, channelId);
      setInfo(r);
      jobSeen.current?.(r.job);
      const mark = r.job ? `${r.job.status}:${r.job.rendered.length}:${r.job.voice.generated}` : "";
      if (seen.current && mark !== seen.current) changed.current?.();
      seen.current = mark;
    } catch { /* the status line is optional; the decision screen stays usable */ }
  };
  useEffect(() => { seen.current = ""; void load(); }, [episodeId, channelId]); // eslint-disable-line react-hooks/exhaustive-deps
  const running = info?.job?.status === "running";
  useEffect(() => {
    if (!running) return;
    const id = setInterval(() => void load(), 2500);
    return () => clearInterval(id);
  }, [running, episodeId, channelId]); // eslint-disable-line react-hooks/exhaustive-deps

  const start = async (opts: { renderOnly?: boolean; voice?: { confirm: true; fingerprint: string } } = {}) => {
    setStarting(true);
    setError("");
    try {
      const r = await api.startScenePrepare(episodeId, channelId, opts);
      setInfo((old) => ({ ...(old ?? { voiceKey: r.voiceKey }), ...r }));
      seen.current = r.job ? `${r.job.status}:${r.job.rendered.length}:${r.job.voice.generated}` : "";
    } catch (e) {
      setError((e as Error).message);
      // VOICE_PLAN_CHANGED: nothing was paid; the new count and cost are read again for a fresh confirmation.
      void load();
    } finally {
      setStarting(false);
    }
  };

  const stop = async () => {
    setError("");
    try {
      const r = await api.stopScenePrepare(episodeId, channelId);
      setInfo((old) => ({ ...(old ?? { voiceKey: r.voiceKey }), ...r }));
    } catch (e) {
      setError((e as Error).message);
    }
  };

  const job = info?.job;
  const allReady = Boolean(prepared && prepared.total > 0 && prepared.ready >= prepared.total);
  const failed = job && !running ? job.failed.length : 0;
  const skipped = job?.skipped ?? [];
  const of = (r: string) => skipped.filter((x) => x.reason === r);
  // QA 12 Nov (balislam 9, zubdat D-7): every scene left undrafted is said with its real reason.
  const waitingVoice = [...of("voice"), ...of("sentences")];
  const afterGap = of("after-gap");
  const held = of("blocked");
  const noKey = Boolean(info && !info.voiceKey && ((info.needVoice ?? 0) > 0 || waitingVoice.length > 0));
  // Audit item 5: never «يولّد الصوت…» when no voice can be made; the blocker is said at once.
  const label = running
    ? noKey ? (job!.sceneId ? `يجهّز ${sceneName(order, job!.sceneId)}…` : "يجهّز…")
    : job!.phase === "voice" && job!.voice.status === "pending" && job!.voice.needed > 0 ? "يولّد الصوت…"
      : job!.sceneId ? `يجهّز ${sceneName(order, job!.sceneId)}…` : "يجهّز…"
    : prepared && prepared.ready > 0 ? "استأنف إنتاج المسودات" : "ابدأ إنتاج المسودات";
  const failedBefore = job && !running ? of("failed-before") : [];
  // M1/M3: a run that finished with a voice error or failed scenes offers «استأنف إنتاج المسودات» (it retries them);
  // so does a run that waited for a voice key once the key is there.
  // The voice itself is offered only by «ولّد الصوت الآن» below (owner decision 15–16 Nov), never by this button.
  const finishedWithErrors = Boolean(job && job.status === "done" && (job.voice.status === "error" || job.failed.length > 0 || failedBefore.length > 0));
  const toneMissing = info?.toneMissing ?? [];
  const named = (m?: string) => nameSceneIds(ownerMessage(m ?? ""), order);
  const list = (xs: { id: string }[]) => sceneNames(order, xs.map((x) => x.id), 3);
  const dot = (t: string) => (/[.…]$/.test(t) ? t : `${t}.`);
  /**
   * What a finished run prepared, and what it did not and why (never a silent «done»): one short line in the header
   * (`summaryShort`), and the whole account in its tooltip (`summary`).
   */
  const finished = Boolean(job && job.status === "done" && !allReady && !failed && job.voice.status !== "error");
  const made = job?.rendered.length ? `جُهّزت ${countAr(job.rendered.length, DRAFTS)}` : "لم تُجهَّز مسودة جديدة";
  const summary = finished ? [
    dot(`انتهى إنتاج المسودات: ${made}`),
    waitingVoice.length ? dot(`${noKey ? "لا يوجد مفتاح صوت فلم يُولَّد صوت؛ " : ""}ينتظر الصوت ${list(waitingVoice)}${of("sentences").length ? " (صوته جملةً جملة في «الجمل»)" : ""}`) : "",
    // D145: no longer produced (every ready scene is drafted, any order); an older job read may still carry it.
    afterGap.length ? `و${ar(afterGap.length)} ${afterGap.length === 1 ? "مشهد جاهز لم يُجهَّز بعد" : "مشاهد جاهزة لم تُجهَّز بعد"}؛ «أنتج كل المشاهد الجاهزة» يجهّزها.` : "",
    held.length ? dot(`${list(held)} ${held.length === 1 ? "ينتظر" : "تنتظر"} إصلاحًا: ${named(held[0]!.error?.split(" — ")[0])}`) : "",
  ].filter(Boolean).join(" ") : "";
  const summaryShort = finished ? `انتهى إنتاج المسودات: ${made}${noKey && waitingVoice.length ? " — لا يوجد مفتاح صوت" : waitingVoice.length ? ` — ينتظر صوت ${list(waitingVoice)}` : held.length ? ` — ${list(held)} ${held.length === 1 ? "ينتظر" : "تنتظر"} إصلاحًا` : ""}` : "";
  return (
    <div className={`prep${className ? ` ${className}` : ""}`} role="group" aria-label="تجهيز المشاهد">
      {prepared ? <span className="prep-count" role="status">جاهز {ar(prepared.ready)} من {ar(prepared.total)}{running ? ` — ${label}` : ""}</span> : null}
      {running ? (
        <button type="button" className="btn ghost" disabled={job?.stopRequested} onClick={() => void stop()}
          title="يُكمل المشهد الجاري ويحفظه، ولا يبدأ غيره؛ والمسودات الجاهزة باقية">
          {job?.stopRequested ? "يتوقف بعد المشهد الجاري…" : "أوقف"}
        </button>
      ) : !allReady && (!job || job.status === "stopped" || job.status === "error" || finishedWithErrors) ? (
        <button type="button" className="btn ghost" disabled={starting} onClick={() => void start()}
          title="يكمل المسودات المجانية للمشاهد التي صوتها جاهز، ولا يولّد صوتًا؛ الاعتماد يبقى لك مشهدًا مشهدًا، بأي ترتيب">
          {starting ? "جارٍ البدء…" : label}
        </button>
      ) : null}
      {/* D145: free renders only — every scene whose voice already exists is drafted; no voice is generated (nothing paid). */}
      {!running && !allReady ? (
        <button type="button" className="btn ghost prep-render-ready" disabled={starting} onClick={() => void start({ renderOnly: true })}
          title="رندر مجاني لكل مشهد صوته جاهز، بأي ترتيب؛ لا يولّد أي صوت. الاعتماد يبقى لك مشهدًا مشهدًا">
          أنتج كل المشاهد الجاهزة
        </button>
      ) : null}
      {starting && !running ? <span className="prep-note" role="status">يبدأ إنتاج المسودات…</span> : null}
      {!running && info?.voicePlan && info.voicePlan.scenes.length > 0 ? (
        <VoicePlanPanel plan={info.voicePlan} order={order} voiceKey={Boolean(info.voiceKey)} busy={starting} onOpenSettings={onOpenSettings}
          onGenerate={(fingerprint) => void start({ voice: { confirm: true, fingerprint } })} />
      ) : null}
      {job?.voice.status === "error" && !running ? (
        // M2 (QA dafatir): the real cause first; the tone choice only when the cause is the missing tone.
        <div className="prep-note is-err prep-error-card" role="alert" title={named(job.voice.error)}>توقف توليد الصوت: {named(job.voice.error?.split("\n")[0])}
          <details><summary>عرض التشخيص</summary><pre>{named(job.voice.error)}</pre></details>
          {toneMissing.length && onEpisodeTone && /نبرة/.test(job.voice.error ?? "")
            ? <> <EpisodeTonePick scenes={toneMissing} order={order} episodeId={episodeId} channelId={channelId} onPick={async (t) => { await onEpisodeTone(t); await load(); }} /></> : null}</div>
      ) : failed ? (
        // KI-012: بطاقة تلتف ولا تُقطع بـ«…»؛ السطر الأول بنص المالك، والتشخيص كاملًا لكل مشهد تحت «عرض التشخيص»
        <div className="prep-note is-err prep-error-card" role="alert">
          تعذّر {countAr(failed, SCENES)} ({sceneName(order, job!.failed[0]!.id)}): <OwnerText text={named(job!.failed[0]!.error.split("\n")[0]!)} />
          <details><summary>عرض التشخيص</summary><pre>{job!.failed.map((f) => `${sceneName(order, f.id)}: ${named(f.error)}`).join("\n\n")}</pre></details>
        </div>
      ) : summary ? (
        <span className="prep-note is-summary" role="status" title={summary}>{summaryShort}{noKey && onOpenSettings ? <> — <button type="button" className="prep-link" onClick={onOpenSettings}>الاتصالات والمفاتيح</button></> : null}</span>
      ) : noKey ? (
        <span className="prep-note">لا يوجد مفتاح صوت: يُجهَّز كل مشهد صوته جاهز، وما ينقصه صوته ينتظر{waitingVoice.length ? ` (${ar(waitingVoice.length)} ينتظر الصوت)` : ""}{onOpenSettings ? <> — <button type="button" className="prep-link" onClick={onOpenSettings}>الاتصالات والمفاتيح</button></> : null}</span>
      ) : failedBefore.length ? (
        <span className="prep-note" title={failedBefore.map((f) => `${sceneName(order, f.id)}: ${named(f.error)}`).join("\n")}>لم يُعَد {sceneName(order, failedBefore[0]!.id)}{failedBefore.length > 1 ? ` و${ar(failedBefore.length - 1)} غيره` : ""}: تعذّر بالمدخلات نفسها في المرة السابقة. «استأنف إنتاج المسودات» يعيد محاولته.</span>
      ) : job?.status === "stopped" ? (
        <span className="prep-note">أُوقف إنتاج المسودات؛ المسودات الجاهزة محفوظة، و«استأنف إنتاج المسودات» يكمل من حيث توقف.</span>
      ) : job?.status === "error" ? (
        <span className="prep-note is-err" role="alert">تعذّر إنتاج المسودات: {named(job.error)}</span>
      ) : null}
      {error ? <span className="prep-note is-err" role="alert"><OwnerText text={error} /></span> : null}
    </div>
  );
};
